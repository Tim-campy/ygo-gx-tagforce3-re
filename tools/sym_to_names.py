"""Turn a PPSSPP .sym file into an ApplyNames.java CSV (address,group,name).

PPSSPP names import stubs from their NIDs ("zz_sceIoRead") and recognises statically linked library
functions by hash. Those names are mapped onto the project's groups (see CLAUDE.md):

- import stubs and Sony's static libraries (sceGu, sceGup, sceVfpu, dl_write_*) -> sdk, name kept;
- VFPU vector/matrix helpers (vadd_q, vector_add_t, matrix_mogrify, ...) -> system, "system_vfpu_<name>";
- everything else PPSSPP knows (libc, libm, newlib reentrant helpers) -> system, "system_<name>".

Unnamed PPSSPP functions ("z_un_<addr>") are emitted with an empty name when --create-unnamed is given,
so ApplyNames.java creates them without naming them. Only addresses inside --range are kept.
"""

import argparse
import re
import sys
from pathlib import Path

LINE = re.compile(r"^([0-9A-Fa-f]{8}) (.+),([0-9A-Fa-f]+)\s*$")
UNNAMED = re.compile(r"^z_un_[0-9a-fA-F]+$")
# Imports PPSSPP cannot name, e.g. a module's imports from the game's own BOOT.BIN library.
UNKNOWN_NID = re.compile(r"^zz_\[UNK: 0x[0-9a-fA-F]+\]$")
SDK = re.compile(r"^(?:_?sce|dl_write_)")
VFPU = re.compile(r"^(?:v[a-z0-9]+_[pqts]|vector_\w+|matrix\w*)$")


def classify(name):
    """Return (group, name) for a PPSSPP symbol, or None for an unnamed one."""
    if UNNAMED.match(name) or UNKNOWN_NID.match(name):
        return None
    if name.startswith("zz_"):
        return "sdk", name[3:]
    if SDK.match(name):
        return "sdk", name
    if VFPU.match(name):
        return "system", "system_vfpu_" + name
    return "system", "system_" + name.lstrip("_")


def parse_range(text):
    start, end = (int(part, 16) for part in text.split("-"))
    return start, end


def main(argv=None):
    parser = argparse.ArgumentParser(description="Convert a PPSSPP .sym file into an ApplyNames CSV.")
    parser.add_argument("sym", type=Path)
    parser.add_argument("--range", type=parse_range, required=True, metavar="START-END",
                        help="hex address range to keep, end exclusive (e.g. 08804000-08872bfc)")
    parser.add_argument("--create-unnamed", action="store_true", help="also emit unnamed functions")
    args = parser.parse_args(argv)
    start, end = args.range

    rows = {}
    for line in args.sym.read_text(encoding="utf-8", errors="replace").splitlines():
        match = LINE.match(line)
        if not match:
            continue
        address = int(match.group(1), 16)
        if not start <= address < end:
            continue
        mapped = classify(match.group(2))
        if mapped:
            rows[address] = mapped
        elif args.create_unnamed:
            rows.setdefault(address, ("", ""))
    print(f"# Generated by tools/sym_to_names.py from {args.sym.name}; do not edit by hand.")
    print("address,group,name")
    for address, (group, name) in sorted(rows.items()):
        print(f"0x{address:08x},{group},{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
